/**
 * Self-host only the Noto Serif SC slices this app's text needs.
 *
 * Google Fonts is not reachable from mainland China, and the full family is
 * ~86 MB across weights. Fontsource splits it into ~100 unicode-range slices;
 * this keeps the 600-weight slices that contain any Han character in the packs,
 * word decks, intro, or UI source. Run after editing sentences:  npm run fonts
 */
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = join(root, "node_modules/@fontsource/noto-serif-sc");
const outDir = join(root, "src/assets/fonts");
const cssOut = join(root, "src/fonts.css");

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

const sources = walk(join(root, "src")).filter((p) => /\.(json|ts|tsx)$/.test(p) && !p.endsWith("t2s.json"));
const needed = new Set();
for (const path of sources) {
  for (const ch of readFileSync(path, "utf8")) {
    const cp = ch.codePointAt(0);
    if (cp >= 0x2e80) needed.add(cp);
  }
}

function ranges(spec) {
  return spec.split(",").map((part) => {
    const [a, b] = part.trim().replace(/^U\+/i, "").split("-");
    const lo = parseInt(a, 16);
    return [lo, b ? parseInt(b, 16) : lo];
  });
}

const css = readFileSync(join(pkg, "600.css"), "utf8");
const blocks = css.split("/* ").filter((b) => b.includes("@font-face"));
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
let kept = "";
let bytes = 0;
let count = 0;
for (const block of blocks) {
  const range = /unicode-range:\s*([^;]+);/.exec(block)?.[1];
  const file = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(block)?.[1];
  if (!range || !file) continue;
  const rs = ranges(range);
  const hit = [...needed].some((cp) => rs.some(([lo, hi]) => cp >= lo && cp <= hi));
  if (!hit) continue;
  copyFileSync(join(pkg, "files", file), join(outDir, file));
  bytes += statSync(join(outDir, file)).size;
  count += 1;
  kept += `@font-face {\n  font-family: "Echo Serif SC";\n  font-style: normal;\n  font-display: swap;\n  font-weight: 600;\n  src: url("./assets/fonts/${file}") format("woff2");\n  unicode-range: ${range};\n}\n`;
}
writeFileSync(
  cssOut,
  `/* Generated by scripts/build-fonts.mjs — Noto Serif SC 600 (SIL OFL 1.1), only the slices this app uses. */\n@import "@fontsource-variable/fraunces/wght.css";\n\n${kept}`,
);
console.log(`fonts: ${count} slices, ${(bytes / 1024).toFixed(0)} KB, ${needed.size} CJK code points`);
